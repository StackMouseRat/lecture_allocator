def db_rows():
    """读 S5 per-girl 排课（全班同班，取 surrey 行）：course -> [(weekday, weeks)]"""
    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row
    data = {}
    for r in conn.execute("SELECT course, weekday, session_weeks FROM girl_course_schedule "
                          "WHERE semester_no=5 AND girl='surrey' ORDER BY weekday"):
        weeks = [int(x) for x in r["session_weeks"].split(",") if x.strip()]
        data.setdefault(r["course"], []).append((r["weekday"], weeks))
    conn.close()
    out = {}
    for c, rows in data.items():
        seen = set()
        out[c] = [(wd, ws) for (wd, ws) in rows if (wd, tuple(ws)) not in seen and not seen.add((wd, tuple(ws)))]
    return out


def build_rows(name, materials, db_course):
    """按 db 行展开 (week, session)。session = 当周按 weekday 升序的序号"""
    wd_by_week = {}
    for wd, weeks in db_course:
        for w in weeks:
            wd_by_week.setdefault(w, []).append(wd)
    for w in wd_by_week:
        wd_by_week[w] = sorted(set(wd_by_week[w]))
    topics = []
    for ch, secs in materials:
        for s in secs:
            topics.append(f"{ch} · {s}")
    n_sessions = sum(len(v) for v in wd_by_week.values())
    assert len(topics) >= n_sessions, \
        f"{name}: 素材{len(topics)} < 行数{n_sessions}"
    rows = []
    idx = 0
    for w in range(1, 17):
        for i, wd in enumerate(wd_by_week.get(w, []), start=1):
            rows.append({"week": w, "session": i, "topic": topics[idx]})
            idx += 1
    return rows


def render_md(name, rows, hps, note=""):
    L = [f"# {name} 授课方案\n"]
    if note:
        L.append(f"{note}\n")
    else:
        L.append(f"> 总学时 {len(rows)*hps} ｜ {len(rows)}次 × {hps}学时/次\n")
    L.append("| 周次 | 节次 | 授课内容 |\n|---|---|---|")
    for r in rows:
        L.append(f"| 第{r['week']}周 | 第{r['session']}节 | {r['topic']} |")
    return "\n".join(L)


def main():
    db = db_rows()
    syllabus = {}
    OUT.mkdir(parents=True, exist_ok=True)
    for name, materials in COURSES.items():
        db_course = db.get(name)
        if db_course is None:
            print(f"  ⚠️ {name}: db 无对应行，跳过")
            continue
        if name == "机电技术创新实训":
            rows = build_rows(name, materials, db_course)
            hours_map = XUNSHI_BLOCK[name]
            total = sum(hours_map[r["week"]] for r in rows)
            note = f"> 总学时 {total} ｜ {len(rows)}天（6 半天×4学时 + 5 全天×8学时）"
            syllabus[name] = {"spw": None, "weeks": 16, "rows": rows, "hps": 8, "hours_map": hours_map}
            (OUT / f"{name}.md").write_text(render_md(name, rows, 8, note), encoding="utf-8")
        elif name in SPECIAL_HOURS:
            rows = build_rows(name, materials, db_course)
            hours_map = SPECIAL_HOURS[name]
            total = sum(hours_map[r["week"]] for r in rows)
            note = f"> 总学时 {total} ｜ {len(rows)}次（{' + '.join(str(hours_map[r['week']]) for r in rows)}学时）"
            syllabus[name] = {"spw": None, "weeks": 16, "rows": rows, "hps": 3, "hours_map": hours_map}
            (OUT / f"{name}.md").write_text(render_md(name, rows, 3, note), encoding="utf-8")
        else:
            # 电力电子实践：8次×2学时（课时减半次数翻倍）；其余实验 4学时、理论/讨论/讲座 2学时
            hps = 2 if name == "电力电子技术基础实践" else (4 if ("实验" in name or "实践" in name) else 2)
            rows = build_rows(name, materials, db_course)
            syllabus[name] = {"spw": None, "weeks": 16, "rows": rows, "hps": hps}
            (OUT / f"{name}.md").write_text(render_md(name, rows, hps), encoding="utf-8")
        print(f"  ✅ {name}: {len(rows)}节 × {'4/8' if name=='机电技术创新实训' else syllabus[name]['hps']}学时")
    (BASE / "data" / "syllabus_sem5.json").write_text(
        json.dumps(syllabus, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\n✅ 共 {len(syllabus)} 门课 → docs/课程进度/sem5/ + data/syllabus_sem5.json")


if __name__ == "__main__":
    main()
