# 课程名 → 渲染课名（syllabus 键必须与 virtual_time 查询名一致）
RENDER_NAMES = {
    "Python语言程序设计": "通识选修·晚间⑦",  # 选修占位符渲染后名
    "改革开放史": "四史·③",   # 占位符（orage 选）
    "新中国史": "四史·④",     # 占位符（sakawa 选）
}


def db_rows():
    """读 S4 排课：course -> [(weekday, weeks)]，按 weekday 排序"""
    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row
    data = {}
    for r in conn.execute("SELECT course, weekday, slot_index, session_weeks FROM virtual_course_schedule "
                          "WHERE semester_no=4 ORDER BY weekday, slot_index"):
        weeks = [int(x) for x in r["session_weeks"].split(",") if x.strip()]
        data.setdefault(r["course"], []).append((r["weekday"], weeks))
    conn.close()
    return data


def build_rows(name, materials, db_course):
    """按 db 行展开 (week, session)。session = 当周按 weekday 升序的序号"""
    # week -> [weekday...]
    wd_by_week = {}
    for wd, weeks in db_course:
        for w in weeks:
            wd_by_week.setdefault(w, []).append(wd)
    for w in wd_by_week:
        wd_by_week[w] = sorted(set(wd_by_week[w]))
    # 素材扁平化
    topics = []
    for ch, secs in materials:
        for s in secs:
            topics.append(f"{ch} · {s}")
    assert len(topics) >= sum(len(v) for v in wd_by_week.values()), \
        f"{name}: 素材{len(topics)} < 行数{sum(len(v) for v in wd_by_week.values())}"
    rows = []
    idx = 0
    for w in range(1, 17):
        for i, wd in enumerate(wd_by_week.get(w, []), start=1):
            rows.append({"week": w, "session": i, "topic": topics[idx % len(topics)]})
            idx += 1
    return rows


def render_md(name, rows, hps=2):
    L = [f"# {name} 授课方案\n",
         f"> 总学时 {len(rows)*hps} ｜ {len(rows)}次 × {hps}学时/次\n",
         "| 周次 | 节次 | 授课内容 |", "|---|---|---|"]
    for r in rows:
        L.append(f"| 第{r['week']}周 | 第{r['session']}节 | {r['topic']} |")
    return "\n".join(L)


def main():
    db = db_rows()
    syllabus = {}
    OUT.mkdir(parents=True, exist_ok=True)
    for name, materials in COURSES.items():
        # db 课名：选修占位符用渲染名
        db_course = None
        dname_target = RENDER_NAMES.get(name, name)
        for dname, rows in db.items():
            if dname == dname_target:
                db_course = rows
                break
        if db_course is None:
            print(f"  ⚠️ {name}: db 无对应行，跳过")
            continue
        hps = 3 if name in ("改革开放史", "新中国史") else (4 if ("实验" in name) else 2)
        rows = build_rows(name, materials, db_course)
        syllabus[name] = {"spw": None, "weeks": 16, "rows": rows, "hps": hps}
        (OUT / f"{name}.md").write_text(render_md(name, rows, hps), encoding="utf-8")
        print(f"  ✅ {name}: {len(rows)}节 × {hps}学时 = {len(rows)*hps}学时")
    (BASE / "data" / "syllabus_sem4.json").write_text(
        json.dumps(syllabus, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\n✅ 共 {len(syllabus)} 门课 → docs/课程进度/sem4/ + data/syllabus_sem4.json")


if __name__ == "__main__":
    main()
