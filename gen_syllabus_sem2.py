def build(course, cfg):
    items = []
    for ch, secs in cfg["chapters"]:
        for s in secs:
            items.append(f"{ch} · {s}")
    rows = []
    idx = 0
    week_seq = cfg.get("weeks_override") or list(range(1, cfg["weeks"] + 1))
    for w in week_seq:
        for s in range(1, cfg["spw"] + 1):
            topic = items[idx % len(items)] if items else "复习与练习"
            rows.append({"week": w, "session": s, "topic": topic})
            idx += 1
    return rows

def render_md(name, cfg, rows):
    L = [f"# {name} 授课方案\n",
         f"> 总学时 {cfg['spw']*cfg['weeks']*2} ｜ 每周 {cfg['spw']} 次 × {cfg['weeks']} 周 ｜ 每次2学时\n",
         "| 周次 | 节次 | 授课内容 |", "|---|---|---|"]
    for r in rows:
        L.append(f"| 第{r['week']}周 | 第{r['session']}节 | {r['topic']} |")
    return "\n".join(L)

syllabus = {}
OUT.mkdir(parents=True, exist_ok=True)
for name, cfg in COURSES.items():
    rows = build(name, cfg)
    syllabus[name] = {"spw": cfg["spw"], "weeks": cfg["weeks"], "rows": rows}
    (OUT / f"{name}.md").write_text(render_md(name, cfg, rows), encoding="utf-8")
    print(f"  ✅ {name}: {len(rows)}节")
(BASE / "data" / "syllabus_sem2.json").write_text(json.dumps(syllabus, ensure_ascii=False, indent=1), encoding="utf-8")
print(f"\n✅ 共 {len(syllabus)} 门课 → docs/课程进度/sem2/ + data/syllabus_sem2.json")
