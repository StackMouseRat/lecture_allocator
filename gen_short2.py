#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""第二小学期（短2）课表生成：机电技术综合实训（96学时）
- 参照短1：排在第1段（过渡周后2周）
- 用户明确：每次都上课一整天、依然排在前半学期 → 96÷8 = 12 天全天
- 第1段 2024-07-01（周一）~ 07-12（周六），连续 12 天，每天上午4学时+下午4学时
- 4 人同班统一实训（工训中心），地点工训中心、老师 T1800
- 输出 girl_schedules/{girl}_short2.md（4 份，标题按人设，正文相同）
用法：python3 gen_short2.py
"""
from pathlib import Path

BASE = Path(__file__).parent
OUT = BASE / "girl_schedules"

GIRLS = {
    "surrey":  ("萨里", "皇家重巡 · 电气工程"),
    "orage":   ("暴风雨", "自由鸢尾驱逐 · 自动化"),
    "sakawa":  ("酒匂", "重樱轻巡 · 测控"),
    "taiyuan": ("太原", "东煌驱逐 · 电气工程"),
}

# 12 天 × 每天（上午/下午 各4学时）= 96 学时
DAYS = [
    ("07-01", "周一", "实训安全教育与工训中心导览", "常用量具使用与机械制图识读"),
    ("07-02", "周二", "车削加工基础（外圆/端面/台阶）", "铣削加工基础（平面/沟槽）"),
    ("07-03", "周三", "钳工基本技能（划线/锯削/锉削）", "装配工艺与精度检测"),
    ("07-04", "周四", "焊接与钣金工艺", "电工接线与配电实训"),
    ("07-05", "周五", "电子元器件识别与焊接", "PCB 制作与电路装配"),
    ("07-06", "周六", "传感器与检测技术应用", "气动与液压传动基础"),
    ("07-08", "周一", "PLC 硬件认识与接线", "PLC 梯形图编程入门"),
    ("07-09", "周二", "电机结构与控制回路", "变频器与调速应用"),
    ("07-10", "周三", "机电综合项目：方案设计与分工", "机电综合项目：部件加工"),
    ("07-11", "周四", "机电综合项目：电气装配", "机电综合项目：程序调试"),
    ("07-12", "周五", "机电综合项目：联调运行", "机电综合项目：故障排查"),
    ("07-13", "周六", "综合项目验收与数据记录", "成果展示与实训报告"),
]

HDR = "| 日期 | 星期 | 上午 08:00-11:40（4学时）| 下午 14:30-17:40（4学时）|"
SEP = "|---|---|---|---|"

for g, (cn, label) in GIRLS.items():
    lines = [f"# {cn}（{label}） · 第二小学期（短2）课表", ""]
    lines.append("> **2024 短2 · 第1段 2024-07-01 ~ 07-13（前半段排完 · 每天一整天）**")
    lines.append("> **机电技术综合实训** ｜ 96学时 = 12天 × 8学时/天 ｜ 工训中心 · T1800 ｜ 4人同班统一实训")
    lines.append("")
    lines.append(HDR)
    lines.append(SEP)
    for d, wd, am, pm in DAYS:
        lines.append(f"| {d} | {wd} | {am} | {pm} |")
    lines.append("")
    lines.append("> 每天上午 4 学时（08:00-11:40）+ 下午 4 学时（14:30-17:40）= 8 学时；07-07 周日休息，07-13 结课")
    lines.append("> 第2段（08-19~09-01）不排课")
    (OUT / f"{g}_short2.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  ✅ {cn}: 机电技术综合实训 12天×8学时 = 96")

print("\n✅ 4份小学期课表已生成 → girl_schedules/{girl}_short2.md")
