def build(course, cfg):
    """章节小节 → 周×节 线性展开"""
    items = []
    for ch, secs in cfg["chapters"]:
        for s in secs:
            items.append(f"{ch} · {s}")
    total = cfg["spw"] * cfg["weeks"]
    # 平均分配：每节占1次课，若不足则重复末章
    rows = []
    idx = 0
    week_seq = cfg.get("weeks_override") or list(range(1, cfg["weeks"] + 1))
    for w in week_seq:
        for s in range(1, cfg["spw"] + 1):
            topic = items[idx % len(items)] if items else "复习与练习"
            rows.append({"week": w, "session": s, "topic": topic})
            idx += 1
    return rows

def render_md(name, cfg, rows):
    L = []
    L.append(f"# {name} 授课方案\n")
    L.append(f"> 总学时 {cfg['spw']*cfg['weeks']*2} ｜ 每周 {cfg['spw']} 次 × {cfg['weeks']} 周 ｜ 每次2学时\n")
    L.append("| 周次 | 节次 | 授课内容 |")
    L.append("|---|---|---|")
    for r in rows:
        L.append(f"| 第{r['week']}周 | 第{r['session']}节 | {r['topic']} |")
    return "\n".join(L)

syllabus = {}
OUT.mkdir(parents=True, exist_ok=True)
